<?php

namespace App\Console\Commands;

use App\Games\BingoPinball\Par;
use App\Games\BingoPinball\Paytables;
use Illuminate\Console\Command;
use Symfony\Component\Console\Output\OutputInterface;

/**
 * Prints the PAR sheet of a Bingo Pinball paytable by enumerating all 53,130 outcomes. Exit code 1 when a computed figure differs from the published one
 * (the counts of the best line, or the RTP of the version): that means a bug in the evaluator or a changed paytable file.
 *
 *   php artisan bingo:par            all versions
 *   php artisan bingo:par 96         one version
 *   php artisan bingo:par --markdown the text of docs/bingo/PAR_SHEETS.md
 */
class BingoPar extends Command
{
    protected $signature = 'bingo:par {version? : 88, 90, 92, 94 or 96 (all when left out)} {--json : machine-readable} {--markdown : the text of docs/bingo/PAR_SHEETS.md}';

    protected $description = 'Bingo Pinball: print the PAR sheet (exact enumeration of all 53,130 outcomes) and check it against the published figures';

    public function handle(): int
    {
        $versions = $this->argument('version') ? [(int) $this->argument('version')] : Paytables::VERSIONS;
        $ok = true;
        $json = [];
        $md = '';
        foreach ($versions as $v) {
            try {
                $p = Paytables::get($v);
            } catch (\InvalidArgumentException $e) {
                $this->error($e->getMessage());

                return self::FAILURE;
            }
            $r = Par::enumerate($p);
            $counts = [5 => $r['byLit'][5], 4 => $r['byLit'][4], 3 => $r['byLit'][3], 0 => $r['byLit'][0] + $r['byLit'][1] + $r['byLit'][2]];
            $match = $counts === Par::PUBLISHED_COUNTS && $r['rtpRounded'] === $p->publishedRtp && $r['outcomes'] === Par::OUTCOMES;
            $ok = $ok && $match;
            if ($this->option('json')) {
                $json[$v] = ['id' => $p->id, 'pays' => $p->pays, 'counts' => $r['byLit'], 'rtp' => $r['rtp'], 'rtpFraction' => $r['rtpFraction'], 'rtpRounded' => $r['rtpRounded'], 'published' => $p->publishedRtp,
                    'hitFrequency' => $r['hitFrequency'], 'standardDeviation' => $r['standardDeviation'], 'matchesPublished' => $match];
            } elseif ($this->option('markdown')) {
                $md = self::markdown($versions);
            } else {
                $this->raw(Par::sheet($p)."\n".($match ? 'MATCHES the published figures.' : 'DOES NOT MATCH the published figures.')."\n\n");
            }
        }
        if ($this->option('json')) {
            $this->raw(json_encode($json, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)."\n");
        } elseif ($this->option('markdown')) {
            $this->raw($md);
        }

        return $ok ? self::SUCCESS : self::FAILURE;
    }

    /** text exactly as it is (no formatting of tags, no wrapping): the sheets are tables */
    private function raw(string $text): void
    {
        $this->getOutput()->write($text, false, OutputInterface::OUTPUT_RAW);
    }

    /** the text of docs/bingo/PAR_SHEETS.md: the PAR sheet of each version (a plain function, so the document can be written without a console) */
    public static function markdown(array $versions = Paytables::VERSIONS): string
    {
        $md = "# Bingo Pinball - PAR sheets\n\nGenerated by `php artisan bingo:par --markdown` (an exact enumeration of all 53,130 outcomes through the game's own evaluator). "
            ."Do not edit by hand: a test (tests/Feature/BingoParCommandTest.php) fails when this file differs from what the command prints.\n\n";
        foreach ($versions as $v) {
            $md .= '## Version '.$v."\n\n```\n".Par::sheet(Paytables::get($v))."```\n\n";
        }

        return $md;
    }
}
